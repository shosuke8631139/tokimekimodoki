# 直線距離 → 車の所要時間の換算。田舎道の平均45km/h・迂回係数1.35
# → 1kmあたり約1.8分。高速がある区間は実際より長めに出る(安全側)。
_MIN_PER_KM = 1.8


def _distance_km(a: tuple[float, float], b: tuple[float, float]) -> float:
    """2点間の直線距離(km)。ハバースイン公式。"""
    lat1, lon1, lat2, lon2 = map(math.radians, (*a, *b))
    h = (math.sin((lat2 - lat1) / 2) ** 2
         + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2)
    return 2 * 6371 * math.asin(math.sqrt(h))


def drive_minutes(address: str | None) -> int | None:
    """住所から自宅(国分)までの車のおよその分数。地名不明なら None。"""
    if not address:
        return None
    for name, coords in TOWN_COORDS:
        if name in address:
            minutes = _distance_km(HOME, coords) * _MIN_PER_KM
            return max(5, int(round(minutes / 5) * 5))  # 5分刻み・最低5分
    return None


def zone_label(minutes: int) -> str:
    """行動圏ルール(30分本命・60分まで)による区分。"""
    if minutes <= 35:
        return "◎30分圏"
    if minutes <= 65:
        return "○60分圏"
    return "△圏外(参考)"


def location_line(address: str | None) -> str | None:
    """通知メールに載せる立地1行。例: 「立地: 国分から車およそ60分 ○60分圏」"""
    minutes = drive_minutes(address)
    if minutes is None:
        return None
    return f"立地: 国分から車およそ{minutes}分 {zone_label(minutes)}"
