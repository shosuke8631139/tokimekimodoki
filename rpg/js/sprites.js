/* ---------- 描画ヘルパ ---------- */

const Sprites = {
  cache: {},

  /* グリッド文字列→オフスクリーンcanvas */
  build(rows, pal, px) {
    const h = rows.length, w = rows[0].length;
    const cv = document.createElement("canvas");
    cv.width = w * px; cv.height = h * px;
    const c = cv.getContext("2d");
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const ch = rows[y][x];
        if (ch === ".") continue;
        const idx = parseInt(ch, 10) - 1;
        c.fillStyle = pal[idx] || pal[pal.length - 1];
        c.fillRect(x * px, y * px, px, px);
      }
    }
    return cv;
  },

  tile(ch) {
    const key = "t_" + ch;
    if (!this.cache[key]) {
      const a = TILE_ART[ch] || TILE_ART["."];
      this.cache[key] = this.build(a.rows, a.pal, 4); // 8x8 → 32px
    }
    return this.cache[key];
  },

  chara(id) {
    const key = "c_" + id;
    if (!this.cache[key]) {
      const def = CHAR_ART[id];
      let rows = def.rows;
      if (!rows) {
        const base = CHAR_ART_BASE[id];
        rows = base ? CHAR_ART[base].rows : MONSTER_ART[id === "priest" ? "mage" : "armor"];
      }
      this.cache[key] = this.build(rows, def.pal, 2); // 16x16 → 32px
    }
    return this.cache[key];
  },

  monster(def) {
    const key = "m_" + def.name;
    if (!this.cache[key]) {
      const scale = def.scale || 4;
      this.cache[key] = this.build(MONSTER_ART[def.art], def.pal, scale);
    }
    return this.cache[key];
  },
};
